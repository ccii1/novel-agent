CREATE TABLE IF NOT EXISTS novels (
 id VARCHAR(36) PRIMARY KEY, title VARCHAR(200) NOT NULL, premise CLOB NOT NULL,
 bible CLOB NOT NULL, status VARCHAR(40) NOT NULL, stage_no INT NOT NULL DEFAULT 1,
 chapter_no INT NOT NULL DEFAULT 1, stage_size INT NOT NULL DEFAULT 10,
 memory_version BIGINT NOT NULL DEFAULT 0, plan CLOB, reflection CLOB,
 novel_budget DECIMAL(14,6) NOT NULL DEFAULT 100, chapter_budget DECIMAL(14,6) NOT NULL DEFAULT 5,
 error CLOB, resume_status VARCHAR(40), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE novels ADD COLUMN IF NOT EXISTS provider VARCHAR(80) NOT NULL DEFAULT 'default';
ALTER TABLE novels ADD COLUMN IF NOT EXISTS model_name VARCHAR(200);
CREATE TABLE IF NOT EXISTS tasks (
 id VARCHAR(36) PRIMARY KEY, novel_id VARCHAR(36), kind VARCHAR(40) NOT NULL,
 task_key VARCHAR(200) NOT NULL UNIQUE, status VARCHAR(30) NOT NULL,
 chapter_no INT NOT NULL, revision INT NOT NULL DEFAULT 0, memory_version BIGINT NOT NULL,
 payload CLOB NOT NULL, result CLOB, error CLOB, available_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS task_status_idx ON tasks(status, created_at);
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS available_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;
CREATE TABLE IF NOT EXISTS chapters (
 novel_id VARCHAR(36) NOT NULL, number INT NOT NULL, stage_no INT NOT NULL,
 revision INT NOT NULL, title VARCHAR(300) NOT NULL, body CLOB NOT NULL,
 summary CLOB, status VARCHAR(30) NOT NULL, memory_version BIGINT NOT NULL,
 published BOOLEAN NOT NULL DEFAULT FALSE,
 PRIMARY KEY(novel_id, number)
);
CREATE TABLE IF NOT EXISTS chapter_history (
 id VARCHAR(36) PRIMARY KEY, novel_id VARCHAR(36) NOT NULL, number INT NOT NULL,
 revision INT NOT NULL, title VARCHAR(300) NOT NULL, body CLOB NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS memories (
 id VARCHAR(36) PRIMARY KEY, novel_id VARCHAR(36) NOT NULL, memory_key VARCHAR(400) NOT NULL,
 kind VARCHAR(30) NOT NULL, chapter_no INT NOT NULL, version BIGINT NOT NULL,
 content CLOB NOT NULL, UNIQUE(novel_id, memory_key, version)
);
CREATE INDEX IF NOT EXISTS memory_version_idx ON memories(novel_id, version);
CREATE TABLE IF NOT EXISTS model_calls (
 id VARCHAR(36) PRIMARY KEY, task_id VARCHAR(36) NOT NULL UNIQUE,
 novel_id VARCHAR(36), chapter_no INT NOT NULL, billing_month VARCHAR(7) NOT NULL,
 status VARCHAR(30) NOT NULL, reserved DECIMAL(14,6) NOT NULL,
 actual DECIMAL(14,6), input_tokens BIGINT, output_tokens BIGINT,
 model VARCHAR(200) NOT NULL, input_price DECIMAL(14,6) NOT NULL, output_price DECIMAL(14,6) NOT NULL,
 response CLOB, error CLOB, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS call_month_idx ON model_calls(billing_month);
ALTER TABLE model_calls ADD COLUMN IF NOT EXISTS skill_version VARCHAR(40);
ALTER TABLE model_calls ADD COLUMN IF NOT EXISTS skill_fingerprint VARCHAR(64);
ALTER TABLE model_calls ADD COLUMN IF NOT EXISTS skill_files CLOB;
ALTER TABLE model_calls ADD COLUMN IF NOT EXISTS request_body CLOB;
ALTER TABLE model_calls ADD COLUMN IF NOT EXISTS provider VARCHAR(80) NOT NULL DEFAULT 'default';
ALTER TABLE model_calls ADD COLUMN IF NOT EXISTS billing_mode VARCHAR(30) NOT NULL DEFAULT 'metered';
CREATE TABLE IF NOT EXISTS chapter_metrics (
 novel_id VARCHAR(36) NOT NULL, chapter_no INT NOT NULL, revision INT NOT NULL,
 characters INT NOT NULL, total_lines INT NOT NULL, dialogue_lines INT NOT NULL,
 dialogue_ratio DOUBLE PRECISION NOT NULL, pacing_data CLOB,
 PRIMARY KEY(novel_id,chapter_no,revision)
);
CREATE TABLE IF NOT EXISTS budget_lock (id INT PRIMARY KEY);
MERGE INTO budget_lock KEY(id) VALUES(1);
CREATE TABLE IF NOT EXISTS research (
 id VARCHAR(36) PRIMARY KEY, task_id VARCHAR(36) NOT NULL UNIQUE, sources CLOB NOT NULL,
 ideas CLOB NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS edit_requests (
 id VARCHAR(36) PRIMARY KEY, novel_id VARCHAR(36) NOT NULL, chapter_no INT NOT NULL,
 base_version BIGINT NOT NULL, instruction CLOB NOT NULL, impact CLOB NOT NULL,
 status VARCHAR(30) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 novel_id VARCHAR(36), task_id VARCHAR(36), type VARCHAR(50) NOT NULL,
 message CLOB NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
